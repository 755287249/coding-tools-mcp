import { runCapturedStdoutWithProgress } from '../../../scripts/run-streamed-child.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = fileURLToPath(new URL('..', import.meta.url));
const worktreeRoot = path.resolve(packageRoot, '..', '..');
const manifest = path.join(worktreeRoot, 'src-tauri', 'Cargo.toml');
const outputFile = path.join(packageRoot, 'src', 'rustCatalog.generated.ts');
const checkOnly = process.argv.includes('--check');

function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.keys(value).sort().map(key => [key, stable(value[key])]));
  }
  return value;
}

process.stderr.write('[sync-rust-catalog] exporting Rust tool catalog\n');
const raw = await runCapturedStdoutWithProgress('cargo', [
  'run', '--quiet', '--no-default-features', '--manifest-path', manifest,
  '--example', 'export_tool_catalog'
], {
  cwd: worktreeRoot,
  label: 'sync-rust-catalog',
  quietHeartbeatMs: 15_000,
  streamStderr: false
});
const exported = JSON.parse(raw.trim());
const behavioralParity = stable(exported.behavioral_parity);
const localChatSkill = exported.local_chat_skill;
if (!localChatSkill?.uri || !localChatSkill?.text) throw new Error("Rust local chat skill is missing");
if (!behavioralParity || typeof behavioralParity !== 'object' || Array.isArray(behavioralParity)) {
  throw new Error('Rust behavioral parity fixture is missing or invalid');
}
const profileNames = ['advanced', 'read-only', 'compat-readonly-all', 'guarded-core', 'trusted-core'];
const namesByProfile = {};
const annotationOverridesByProfile = {};
const revisions = {};
let advancedCatalog;
let advancedByName;
for (const profile of profileNames) {
  const entry = exported.profiles?.[profile];
  const catalog = entry?.tools;
  const revision = String(entry?.toolset_revision ?? '');
  if (!Array.isArray(catalog) || catalog.length === 0) {
    throw new Error(`Rust ${profile} catalog is missing or empty`);
  }
  if (!/^[0-9a-f]{16}$/.test(revision)) throw new Error(`Rust toolset revision is invalid for ${profile}`);
  const seen = new Set();
  for (const tool of catalog) {
    if (!tool || typeof tool.name !== 'string' || seen.has(tool.name)) throw new Error(`Rust ${profile} catalog contains an invalid or duplicate tool`);
    seen.add(tool.name);
  }
  if (profile === 'advanced') {
    advancedCatalog = stable(catalog);
    advancedByName = new Map(advancedCatalog.map(tool => [tool.name, tool]));
  }
  namesByProfile[profile] = catalog.map(tool => tool.name);
  revisions[profile] = revision;
}

for (const profile of profileNames) {
  const overrides = {};
  for (const tool of exported.profiles[profile].tools) {
    const base = advancedByName.get(tool.name);
    if (!base) throw new Error(`Rust ${profile} catalog references a tool absent from advanced: ${tool.name}`);
    const { annotations: baseAnnotations, ...baseContract } = base;
    const { annotations, ...profileContract } = stable(tool);
    if (JSON.stringify(profileContract) !== JSON.stringify(baseContract)) {
      throw new Error(`Rust ${profile} changes the non-annotation contract for ${tool.name}`);
    }
    if (JSON.stringify(annotations) !== JSON.stringify(baseAnnotations)) overrides[tool.name] = annotations;
  }
  annotationOverridesByProfile[profile] = overrides;
}

const content = [
  '// Generated by scripts/sync-rust-catalog.mjs. Do not edit manually.',
  "import type { ToolDefinition, ToolProfile } from './types.js';",
  '',
  `export const localChatSkill = ${JSON.stringify(localChatSkill, null, 2)} as const;`,
  '',
  `export const rustCatalog: readonly ToolDefinition[] = ${JSON.stringify(advancedCatalog, null, 2)};`,
  `export const rustToolNamesByProfile: Readonly<Record<ToolProfile, readonly string[]>> = ${JSON.stringify(namesByProfile, null, 2)};`,
  `export const rustToolAnnotationOverridesByProfile: Readonly<Record<ToolProfile, Readonly<Record<string, ToolDefinition['annotations']>>>> = ${JSON.stringify(annotationOverridesByProfile, null, 2)};`,
  `export const rustToolsetRevisionByProfile: Readonly<Record<ToolProfile, string>> = ${JSON.stringify(revisions, null, 2)};`,
  `export const rustBehavioralParityFixtures: Readonly<Record<string, unknown>> = ${JSON.stringify(behavioralParity, null, 2)};`,
  ''
].join('\n');
if (checkOnly) {
  let current = '';
  try { current = await readFile(outputFile, 'utf8'); } catch { /* missing file is drift */ }
  if (current.replaceAll('\r\n', '\n') !== content) {
    throw new Error('generated Node tool catalog differs from the Rust registry; run pnpm run sync:rust-contract');
  }
  console.log('Node tool catalog exactly matches the Rust registry');
} else {
  await writeFile(outputFile, content);
  console.log(`generated ${path.relative(worktreeRoot, outputFile)} from ${profileNames.length} Rust tool profiles`);
}

// Keep the GET/file instructions in a single packaged source, including portable builds.
const compatSource = await readFile(new URL('../../../skills/chat-get-compat/SKILL.md', import.meta.url), 'utf8');
const compatOutput = new URL('../src/chat/compat-skill.generated.ts', import.meta.url);
const compatContent = '// Generated from skills/chat-get-compat/SKILL.md.\nexport const compatSkill = ' + JSON.stringify(compatSource.replace(/\r\n/g, '\n')) + ';\n';
if (process.argv.includes('--check')) {
  if ((await readFile(compatOutput, 'utf8')).replace(/\r\n/g, '\n') !== compatContent) throw new Error('GET compatibility skill is stale; run sync:rust-contract');
} else await writeFile(compatOutput, compatContent);
